def edition_to_json(ed):
    return {
        "year": ed["year"],
        "stichtag": ed["stichtag"],
        "source": f"data/raw/mietspiegeltabelle{ed['year']}.pdf (official, mietspiegel.berlin.de)",
        "cohorts": ed["cohorts"],
        "rows": [
            {"lage": lage, "size": size, "values": [
                {"mittelwert": v[0], "untere": v[1], "obere": v[2]} if v else None
                for v in values
            ]}
            for lage, size, values in ed["rows"]
        ],
    }


def newest_cohort_mean(ed, lage):
    """Mean of Mittelwerte in the newest (last) cohort across size bands."""
    idx = len(ed["cohorts"]) - 1
    vals = [row["values"][idx]["mittelwert"] for row in ed["rows"]
            if row["lage"] == lage and row["values"][idx]]
    return round(sum(vals) / len(vals), 2) if vals else None


def main():
    out = {
        "schema": "official-edition-transcription-v1",
        "note": ("Manual transcription from official PDFs. Every value read from "
                 "the PDF text layer. by_lage = mean of Mittelwerte in the "
                 "newest cohort across its size bands (documented derivation). "
                 "2013/2015 not in the official archive — series starts 2017."),
        "editions": [edition_to_json(e) for e in (ED2017, ED2019, ED2021)],
        "by_lage_series": {},
    }
    for e in (ED2017, ED2019, ED2021):
        out["by_lage_series"][e["year"]] = {
            lage: newest_cohort_mean(edition_to_json(e), lage)
            for lage in ("einfach", "mittel", "gut")
        }
    p = REPO / "docs/data/processed/berlin_historical_editions_old.json"
    p.write_text(json.dumps(out, ensure_ascii=False, indent=2))
    print("wrote", p)
    print(json.dumps(out["by_lage_series"], indent=1))


if __name__ == "__main__":
    main()
